"""Generate LaTeX tables for the documentation from docs/data/*.yaml.

Run from the repository root:  uv run docs/tools/gen_tex.py
The generated files live in docs/latex/common/generated/ and are committed;
CI fails if they are out of date.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "docs" / "data"
OUT = ROOT / "docs" / "latex" / "common" / "generated"
OPENAPI = ROOT / "desktop" / "src" / "lib" / "api" / "openapi.json"

_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def tex(value: Any) -> str:
    """Escape a value for use in LaTeX body text."""
    return "".join(_ESCAPES.get(char, char) for char in str(value))


def longtable(spec: str, header: list[str], rows: list[list[str]]) -> str:
    head = " & ".join(rf"\textbf{{{tex(cell)}}}" for cell in header) + r" \\"
    lines = [
        "% Generated by docs/tools/gen_tex.py -- do not edit by hand.",
        rf"\begin{{longtable}}{{{spec}}}",
        r"\toprule",
        head,
        r"\midrule",
        r"\endhead",
    ]
    lines += [" & ".join(row) + r" \\" for row in rows]
    lines += [r"\bottomrule", r"\end{longtable}", ""]
    return "\n".join(lines)


def requirement_rows(items: list[dict[str, Any]], with_meta: bool) -> list[list[str]]:
    rows: list[list[str]] = []
    for item in items:
        row = [rf"\texttt{{{tex(item['id'])}}}", rf"\textbf{{{tex(item['title'])}}}. {tex(item['text'])}"]
        if with_meta:
            row += [tex(item["priority"]), tex(item["milestone"])]
        rows.append(row)
    return rows


def main() -> None:
    requirements = yaml.safe_load((DATA / "requirements.yaml").read_text(encoding="utf-8"))
    project = yaml.safe_load((DATA / "project.yaml").read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)

    wide = r"@{}P{0.15\linewidth}P{0.55\linewidth}P{0.09\linewidth}P{0.09\linewidth}@{}"
    outputs = {
        "constraints.tex": longtable(
            r"@{}P{0.13\linewidth}P{0.83\linewidth}@{}",
            ["ID", "Constraint"],
            requirement_rows(requirements["constraints"], with_meta=False),
        ),
        "requirements-functional.tex": longtable(
            wide,
            ["ID", "Requirement", "Priority", "Milestone"],
            requirement_rows(requirements["functional"], with_meta=True),
        ),
        "requirements-nonfunctional.tex": longtable(
            wide,
            ["ID", "Requirement", "Priority", "Milestone"],
            requirement_rows(requirements["non_functional"], with_meta=True),
        ),
        "milestones.tex": longtable(
            # Widths leave room for the column separation (6 x \tabcolsep).
            r"@{}P{0.07\linewidth}P{0.29\linewidth}P{0.08\linewidth}P{0.48\linewidth}@{}",
            ["ID", "Milestone", "Effort", "Goal"],
            [
                [tex(m["id"]), tex(m["name"]), tex(m["effort"]), tex(m["goal"])]
                for m in project["milestones"]
            ],
        ),
        "risks.tex": longtable(
            r"@{}P{0.06\linewidth}P{0.28\linewidth}P{0.1\linewidth}P{0.08\linewidth}P{0.36\linewidth}@{}",
            ["ID", "Risk", "Likelihood", "Impact", "Mitigation"],
            [
                [tex(r["id"]), tex(r["risk"]), tex(r["likelihood"]), tex(r["impact"]), tex(r["mitigation"])]
                for r in project["risks"]
            ],
        ),
    }
    if OPENAPI.exists():
        import json

        spec = json.loads(OPENAPI.read_text(encoding="utf-8"))
        rows = []
        for path, methods in sorted(spec["paths"].items()):
            for method, operation in methods.items():
                summary = operation.get("summary") or operation.get("operationId", "")
                rows.append(
                    [rf"\texttt{{{method.upper()}}}", rf"\texttt{{{tex(path)}}}", tex(summary)]
                )
        outputs["api-endpoints.tex"] = longtable(
            r"@{}P{0.1\linewidth}P{0.42\linewidth}P{0.42\linewidth}@{}",
            ["Method", "Path", "Operation"],
            rows,
        )
    for name, content in outputs.items():
        (OUT / name).write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT) / name}")


if __name__ == "__main__":
    main()
